export function resolveSpecialistId(idOrAlias: string): string {
  if (!idOrAlias) return 'orchestrator';
  return SPECIALIST_ALIAS_MAP[idOrAlias] || idOrAlias;
}

export function getSpecialists(domain?: string): AgentSummary[] {
  if (!domain || domain === 'all') {
    return SPECIALISTS_CATALOG;
  }
  return SPECIALISTS_CATALOG.filter((s) => s.domain === domain);
}

export function getSpecialistById(idOrAlias: string): AgentSummary | undefined {
  const resolvedId = resolveSpecialistId(idOrAlias);
  return (
    SPECIALISTS_CATALOG.find((s) => s.id === resolvedId) ||
    SPECIALISTS_CATALOG.find((s) => s.id === idOrAlias)
  );
}

export function getSkills(domain?: string): SkillSummary[] {
  if (!domain || domain === 'all') {
    return SKILLS_CATALOG;
  }
  return SKILLS_CATALOG.filter((s) => s.domain === domain);
}

export function getSkillById(id: string): SkillSummary | undefined {
  return SKILLS_CATALOG.find((s) => s.id === id);
}

export function getAllSpecialists(): AgentSummary[] {
  return SPECIALISTS_CATALOG;
}

export function getAllSkills(): SkillSummary[] {
  return SKILLS_CATALOG;
}

